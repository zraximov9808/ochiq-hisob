"""Builds src/engine/chart.ts from scripts/chart-draft.tsv (codes, kinds, Russian names from the 1C export)
and scripts/chart-uz*.tsv (Uzbek names). Every code must have exactly one Uzbek name."""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
draft = [l.split('\t') for l in (root / 'scripts' / 'chart-draft.tsv').read_text(encoding='utf-8').splitlines() if l.strip()]
uz = {}
for f in sorted((root / 'scripts').glob('chart-uz*.tsv')):
    for line in f.read_text(encoding='utf-8').splitlines():
        if not line.strip():
            continue
        code, name = line.split('\t', 1)
        if code in uz:
            sys.exit(f'duplicate translation for {code} in {f.name}')
        uz[code] = name.strip()

missing = [d[0] for d in draft if d[0] not in uz]
extra = sorted(set(uz) - {d[0] for d in draft})
if missing or extra:
    sys.exit(f'missing: {missing[:20]} extra: {extra[:20]}')

lines = []
for code, kind, cur, ru, _old in draft:
    for part in (uz[code], ru):
        if '|' in part or '`' in part or '${' in part:
            sys.exit(f'bad character in {code}: {part}')
    lines.append(f'{code}|{kind}|{cur}|{uz[code]}|{ru}')

body = '\n'.join(lines)
ts = f'''/**
 * Chart of accounts: the 1C chart for Uzbekistan (BHMS 21 with sub-accounts), generated by scripts/build_chart.py.
 * Line format: code|kind|currency|Uzbek name|Russian name. Kind: A asset, P liability, T transit (P&L),
 * KA contra-asset, Z off-balance, empty when the export gives none; currency "+" marks currency accounts.
 * Uzbek names are written with plain apostrophes and normalised to oʻ/gʻ and ’ when loaded.
 */
export const CHART_SOURCE = `
{body}
`;
'''
(root / 'src' / 'engine' / 'chart.ts').write_text(ts, encoding='utf-8', newline='\n')
print(len(lines), 'accounts written')
